//! # 配置渲染
//!
//! 把数据库里的整棵子树（实例 → 监听器 → 路由，加实例级的负载均衡器）渲染成
//! 一份可以直接写进 Consul KV 的 TOML。
//!
//! ## 为什么渲染「完整 TOML」而不是增量补丁
//!
//! gatex 的 `listeners` 是**整段替换**语义：KV 里是什么，网关就装什么。所谓
//! 「只改一条路由就推一条路由」没有对应的接口，硬做就是在网关侧维护一份 diff
//! 状态，一旦推一半失败就永久漂移。所以每次发布都从库里重新渲染整份。
//!
//! ## 三条硬规则
//!
//! 1. **不拼字符串**。结构化部分序列化出来，`extra_toml` 用 [`toml::Value`]
//!    合并，绝不 `format!` 拼接——拼接会把语法错误留到网关启动时才炸。
//! 2. **不自己定义「像 gatex 的」结构**。配置类型直接引 `gatex-svr::config`，
//!    渲染结果再 `toml::from_str::<AppConfig>` 读回来。管理面和网关共用同一份
//!    定义，「管理面说能发布」才等于「网关能装起来」。
//! 3. **渲染完必须过 [`validate_app_config`]**。它走的是网关启动时同一段
//!    `build`，只是不绑定端口、不注册后台服务。
//!
//! ## 顺序即语义
//!
//! 监听器按 `(sort_no, id)` 排，路由按 `(sort_no, id)` 排。`sort_no` 允许重复
//! （改顺序时不必腾挪临时值），用 `id` 兜底保证**同一份数据每次渲染出同一个字节流**
//! ——`checksum` 才可能稳定，「内容没变就不重复推」才成立。
//!
//! ## 分层
//!
//! - [`renderable`]：可序列化的镜像结构 + 渲染输入
//! - [`pipeline`]：渲染 → 合并 → 自检 → 试装配 → 结构比对
//! - [`import`]：反向——把一份现成的 TOML 拆回结构化数据，并用「模拟渲染 +
//!   往返比对」保证拆得无损
//! - [`error`]：渲染期错误

