use robotech::macros::svc;

/// # 网关发布版本业务层
///
/// 一期的 CRUD 全部由 `#[svc]` 生成，这里先只放骨架。
///
/// 这张表最终**不靠通用 CRUD 写入**——真正的入口是「发布」动作，它在一个流程里
/// 完成：读整棵子树 → 渲染 → 校验 → 分配版本号 → 落库 → 推 Consul → 回填
/// `pushed`。通用 `add` 保留只是为了联调和补数据。
///
/// 后续会补四类能力：
///
/// 1. **`publish`**：渲染 + 落库 + 推送 + 回填，整条链路。`checksum` 与上一版
///    相同则直接返回「无变更」，不产生新版本。
/// 2. **`rollback`**：取历史 `content` 原样 PUT，**不重新渲染**。是否生成新版本
///    记录取决于产品口径——按「发布即一条记录」的原则，回滚也是一次发布，
///    版本号继续递增，`content` 是旧的那一份。
/// 3. **版本号分配**：`max(version) + 1`，靠 `(gateway_id, version)` 唯一键
///    兜住并发冲突，撞了重试。
/// 4. **`content` 校验**：落库前用 `toml::from_str::<AppConfig>` 自检一遍，
///    渲染出来的东西自己都读不回来就不能推出去。
